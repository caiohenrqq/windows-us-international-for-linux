#!/usr/bin/env python3
import argparse
from pathlib import Path


POLICIES = (
    ("dead_acute", "'", "aAcCeEiIoOuUyY", "áÁçÇéÉíÍóÓúÚýÝ"),
    ("dead_diaeresis", '"', "aAeEiIoOuUy", "äÄëËïÏöÖüÜÿ"),
    ("dead_grave", "`", "aAeEiIoOuU", "àÀèÈìÌòÒùÙ"),
    ("dead_tilde", "~", "aAnNoO", "ãÃñÑõÕ"),
    ("dead_circumflex", "^", "aAeEiIoOuU", "âÂêÊîÎôÔûÛ"),
)
ALTGR_CHARACTERS = "¡²³¤€¼½¾‘’¥×¹£÷äåé®þüúíóö«»ÄÅÉÞÜÚÍÓÖáßðø¶´¬Á§ÐØ°¨¦æ©ñµç¿Æ¢ÑÇ"
PUNCTUATION_NAMES = dict(zip(
    " !\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~",
    ("space exclam quotedbl numbersign dollar percent ampersand apostrophe "
     "parenleft parenright asterisk plus comma minus period slash colon semicolon "
     "less equal greater question at bracketleft backslash bracketright "
     "asciicircum underscore grave braceleft bar braceright asciitilde").split(),
    strict=True,
))


def keysym(character):
    if character.isascii():
        return PUNCTUATION_NAMES.get(character, character)
    return f"U{ord(character):04X}"


def quote(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def generate():
    lines = [
        "# Generated by tools/generate_compose.py; edit the policies there.",
        "# Microsoft US-International, KLID 00020409.",
        "# Multi_key and mixed dead-key sequences are intentionally untouched.",
        "",
    ]
    characters = sorted(set(map(chr, range(32, 127))) | set(ALTGR_CHARACTERS))
    for dead, punctuation, letters, accents in POLICIES:
        mappings = dict(zip(letters, accents, strict=True))
        lines.append(f"# {dead}")
        for character in characters:
            if character in "'\"`~^":
                continue
            result = punctuation if character == " " else mappings.get(
                character, punctuation + character)
            lines.append(f'<{dead}> <{keysym(character)}> : "{quote(result)}"')
        lines.extend((f'<{dead}> <{dead}> : "{quote(punctuation * 2)}"', ""))
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = Path(__file__).resolve().parents[1] / "data/compose/windows-us-intl"
    expected = generate()
    if args.check:
        if destination.read_text() != expected:
            parser.exit(1, "Compose data is stale; run tools/generate_compose.py\n")
    else:
        destination.write_text(expected)
